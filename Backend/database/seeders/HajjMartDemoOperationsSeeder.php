    public function run(): void
    {
        DB::transaction(function (): void {
            $shop = Shop::defaultStore();
            $admin = User::where('email', 'admin@hajjmart.local')->firstOrFail();
            $orderList = OrderList::firstOrCreate(['shop_id' => $shop->id]);

            $this->resetSeededOperations();
            $employees = $this->seedEmployees($shop, $admin);
            $customers = $this->seedCustomers();
            $products = Product::with(['productVariants', 'productImages', 'primaryCategory'])->where('is_active', true)->get();
            if ($products->isEmpty()) {
                throw new \RuntimeException('No products are available. Run HajjMartProductSeeder before HajjMartDemoOperationsSeeder.');
            }

            $orders = $this->seedOrders($products, $customers, $orderList, $shop, $admin, $employees);
            $this->seedReturns($orders, $products, $shop, $admin);
            $this->seedTransactions($shop, $admin, $employees);
            $this->resetEverySellableSkuToFifty($products, $shop, $admin);
            $this->seedDailySummaries();
        });

        $this->command?->info('Seeded 300 orders, 20 return/exchange/refunds, 15 employees, 3 roles, transactions, and direct batches with 50 units per sellable SKU.');
    }

    private function resetSeededOperations(): void
    {
        Order::where('source_reference', 'like', 'SEED-%')->get()->each->delete();
        BusinessTransaction::where('reference', 'like', 'SEED-%')->get()->each->delete();
        User::withTrashed()->where('email', 'like', 'employee%@hajjmart.local')->get()->each(fn (User $user) => $user->forceDelete());
        User::withTrashed()->where('email', 'like', 'demo.customer%@hajjmart.local')->get()->each(fn (User $user) => $user->forceDelete());
        StockMovement::where('reason_code', 'seed_stock_50')->delete();
        ProductBatch::where('batch_reference', 'like', 'SEED-DEMO-%')->delete();
    }

    private function seedEmployees(Shop $shop, User $admin)
    {
        $roles = Role::whereIn('slug', ['store_manager', 'sales_order_operator', 'inventory_manager'])->get()->keyBy('slug');
        if ($roles->count() !== 3) {
            throw new \RuntimeException('The three operational roles are missing. Run AdminAccessSeeder first.');
        }

        return collect(range(1, 15))->map(function (int $index) use ($shop, $admin, $roles): User {
            $roleSlug = match (true) {
                $index <= 5 => 'store_manager',
                $index <= 10 => 'sales_order_operator',
                default => 'inventory_manager',
            };
            $role = $roles[$roleSlug];
            $name = $this->firstNames[$index - 1] . ' ' . $this->lastNames[$index % count($this->lastNames)];
            $employee = User::updateOrCreate(
                ['email' => sprintf('employee%02d@hajjmart.local', $index)],
                [
                    'name' => $name,
                    'phone' => '01710' . str_pad((string) $index, 6, '0', STR_PAD_LEFT),
                    'password' => Hash::make('ChangeMe123!'),
                    'role' => 'employee',
                    'is_active' => true,
                    'employee_code' => sprintf('HM-EMP-%03d', $index),
                    'designation' => $role->name,
                    'employment_type' => $index % 5 === 0 ? 'part_time' : 'full_time',
                    'shop_id' => $shop->id,
                    'joined_at' => now()->subMonths(($index % 8) + 1)->toDateString(),
                    'created_by' => $admin->id,
                    'notes' => 'Deterministic demonstration employee generated by HajjMartDemoOperationsSeeder.',
                ]
            );
            $employee->roles()->sync([$role->id]);
            return $employee;
        });
    }

