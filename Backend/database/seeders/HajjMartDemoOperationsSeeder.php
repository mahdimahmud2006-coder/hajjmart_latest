        }

        if ($coupon) {
            $coupon->update(['used_count' => $couponUses]);
        }

        return $orders;
    }

    private function seedReturns($orders, $products, Shop $shop, User $admin): void
    {
        $eligible = $orders->filter(fn (Order $order) => in_array($order->status, ['delivered', 'completed'], true) && $order->items->isNotEmpty())->take(20)->values();

        foreach ($eligible as $index => $order) {
            $isRefund = $index < 10;
            $item = $order->items->first();
            $amount = round((float) $item->line_grand_total / max(1, (int) $item->quantity), 2);
            $createdAt = Carbon::parse($order->created_at)->addDays(2);
            $exchangeProduct = $products[($index * 7 + 3) % $products->count()];
            $exchangeVariant = $exchangeProduct->productVariants->first();
            $exchangePrice = (float) ($exchangeVariant?->sale_price ?: $exchangeVariant?->price ?: $exchangeProduct->sale_price ?: $exchangeProduct->selling_price ?: $amount);
            $difference = round($exchangePrice - $amount, 2);

            $return = ReturnRequest::create([
                'rr_number' => 'RR-DEMO-' . str_pad((string) ($index + 1), 3, '0', STR_PAD_LEFT),
                'order_id' => $order->id,
                'customer_id' => $order->customer_id,
                'type' => $isRefund ? 'return' : 'exchange',
                'status' => 'completed',
                'reason' => $isRefund ? 'Size or product preference changed' : 'Customer requested another variation',
                'customer_note' => 'Demonstration return/exchange request.',
                'admin_note' => 'Inspected and completed by seeded administrator.',
                'approved_by' => $admin->id,
                'approved_at' => $createdAt->copy()->addHour(),
                'refund_total' => $isRefund ? $amount : max(0, -$difference),
                'exchange_credit_total' => $isRefund ? 0 : $amount,
                'exchange_due_total' => $isRefund ? 0 : max(0, $difference),
                'promotion_adjustment_total' => 0,
                'resolved_at' => $createdAt->copy()->addHours(3),
                'shop_id' => $shop->id,
                'created_by' => $admin->id,
                'resolution_type' => $isRefund ? 'refund' : 'exchange',
                'refund_method' => $isRefund ? ($order->payment_method ?: 'cash') : null,
                'restock_strategy' => $index % 4 === 0 ? 'damaged' : 'sellable',
                'created_at' => $createdAt,
                'updated_at' => $createdAt,
            ]);
            $return->forceFill(['created_at' => $createdAt, 'updated_at' => $createdAt])->saveQuietly();

            ReturnRequestItem::create([
                'return_request_id' => $return->id,
                'order_item_id' => $item->id,
                'quantity' => 1,
                'reason' => $return->reason,
                'condition_note' => $index % 4 === 0 ? 'Packaging opened; route to damaged inspection.' : 'Unused and sellable.',
                'exchange_product_id' => $isRefund ? null : $exchangeProduct->id,
                'exchange_variant_id' => $isRefund ? null : $exchangeVariant?->id,
                'unit_price' => $amount,
                'line_subtotal' => $amount,
                'prorated_discount_amount' => 0,
                'refundable_amount' => $isRefund ? $amount : 0,
                'exchange_unit_price' => $isRefund ? 0 : $exchangePrice,
                'exchange_line_total' => $isRefund ? 0 : $exchangePrice,
                'exchange_price_difference' => $isRefund ? 0 : $difference,
                'exchange_amount_due' => $isRefund ? 0 : max(0, $difference),
                'exchange_refund_due' => $isRefund ? 0 : max(0, -$difference),
            ]);

            ReturnStatusHistory::create([
                'return_request_id' => $return->id,
                'from_status' => 'approved',
                'to_status' => 'completed',
                'changed_by' => $admin->id,
                'note' => $isRefund ? 'Refund completed.' : 'Exchange completed.',
                'created_at' => $createdAt->copy()->addHours(3),
            ]);

            if ($isRefund) {
                $item->update([
                    'refunded_quantity' => 1,
                    'refunded_amount' => $amount,
                    'item_status' => 'refunded',
                ]);
                $order->increment('refund_total', $amount);
                $payment = $order->payments->first();
                if ($payment) {
                    $payment->update([
                        'refunded_amount' => $amount,
                        'refund_status' => $amount >= (float) $payment->amount ? 'full' : 'partial',
                    ]);
                }
            } else {
                $item->update(['exchanged_quantity' => 1, 'item_status' => 'exchanged']);
                if ($difference > 0) {
                    $order->increment('exchange_due_total', $difference);
                }
            }
        }
    }

    private function seedTransactions(Shop $shop, User $admin, $employees): void
    {
        $expenseReasons = [
            ['Utilities', 'Electricity bill for the retail store'],
            ['Delivery', 'Local delivery and courier settlement'],
            ['Maintenance', 'Air conditioner and lighting maintenance'],
            ['Marketing', 'Social media campaign and product photography'],
            ['Supplies', 'Packaging bags, tape and invoice paper'],
            ['Transport', 'Product collection transport expense'],
        ];

        for ($i = 1; $i <= 30; $i++) {
            [$category, $reason] = $expenseReasons[($i - 1) % count($expenseReasons)];
            $type = $i % 10 === 0 ? 'income' : 'expense';
            BusinessTransaction::create([
                'transaction_number' => 'TXN-SEED-' . str_pad((string) $i, 4, '0', STR_PAD_LEFT),
                'shop_id' => $shop->id,
                'type' => $type,
                'category' => $type === 'income' ? 'Other income' : $category,
                'amount' => $type === 'income' ? 1500 + ($i * 50) : 300 + (($i * 173) % 3700),
                'payment_method' => ['cash', 'bkash', 'bank'][$i % 3],
                'reason' => $type === 'income' ? 'Recovered delivery adjustment and miscellaneous income.' : $reason,
                'reference' => 'SEED-TXN-' . str_pad((string) $i, 3, '0', STR_PAD_LEFT),
                'occurred_at' => now()->subDays(30 - $i)->setTime(12, ($i * 3) % 60),
                'status' => 'recorded',
                'created_by' => $employees[($i - 1) % $employees->count()]->id,
                'approved_by' => $admin->id,
                'meta' => ['seeded' => true],
                'created_at' => now()->subDays(30 - $i),
                'updated_at' => now()->subDays(30 - $i),
            ]);
        }
    }

    private function resetEverySellableSkuToFifty($products, Shop $shop, User $admin): void
    {
        foreach ($products as $product) {
            if ($product->productVariants->isNotEmpty()) {
                Inventory::updateOrCreate(
                    ['product_id' => $product->id, 'variant_id' => null, 'shop_id' => $shop->id],
                    ['quantity' => 0, 'reserved' => 0, 'low_stock_threshold' => 5, 'updated_at' => now()]
                );
                foreach ($product->productVariants as $variant) {
                    $inventory = Inventory::updateOrCreate(
                        ['product_id' => $product->id, 'variant_id' => $variant->id, 'shop_id' => $shop->id],
                        ['quantity' => 50, 'reserved' => 0, 'low_stock_threshold' => 5, 'updated_at' => now()]
                    );
                    ProductBatch::updateOrCreate(
                        ['batch_reference' => 'SEED-DEMO-' . $shop->id . '-' . $product->id . '-' . $variant->id],
                        [
                            'product_id' => $product->id,
                            'variant_id' => $variant->id,
                            'shop_id' => $shop->id,
                            'count' => 50,
                            'initial_quantity' => 50,
                            'cost_price' => $variant->cost_price ?: $product->cost_price ?: 0,
                            'selling_price' => $variant->sale_price ?: $variant->price ?: $product->selling_price ?: 0,
                            'created_by' => $admin->id,
                            'note' => 'Direct batch generated by HajjMartDemoOperationsSeeder.',
                            'received_at' => now(),
                        ]
                    );
                    $variant->update([
                        'in_stock' => true,
                        'purchasable' => true,
                        'available_for_purchase' => true,
                    ]);
                    StockMovement::create([
                        'inventory_id' => $inventory->id,
                        'type' => 'adjustment',
                        'quantity_change' => 0,
                        'reference_type' => 'database_seed',
                        'reference_id' => null,
                        'note' => 'Seeder normalized this variation to 50 units.',
                        'created_by' => $admin->id,
                        'created_at' => now(),
                        'shop_id' => $shop->id,
                        'balance_after' => 50,
                        'reason_code' => 'seed_stock_50',
                    ]);
                }
            } else {
                $inventory = Inventory::updateOrCreate(
                    ['product_id' => $product->id, 'variant_id' => null, 'shop_id' => $shop->id],
                    ['quantity' => 50, 'reserved' => 0, 'low_stock_threshold' => 5, 'updated_at' => now()]
                );
                ProductBatch::updateOrCreate(
                    ['batch_reference' => 'SEED-DEMO-' . $shop->id . '-' . $product->id . '-0'],
                    [
                        'product_id' => $product->id,
                        'variant_id' => null,
                        'shop_id' => $shop->id,
                        'count' => 50,
                        'initial_quantity' => 50,
                        'cost_price' => $product->cost_price ?: 0,
                        'selling_price' => $product->sale_price ?: $product->selling_price ?: 0,
                        'created_by' => $admin->id,
                        'note' => 'Direct batch generated by HajjMartDemoOperationsSeeder.',
                        'received_at' => now(),
                    ]
                );
                StockMovement::create([
                    'inventory_id' => $inventory->id,
                    'type' => 'adjustment',
                    'quantity_change' => 0,
                    'reference_type' => 'database_seed',
                    'reference_id' => null,
                    'note' => 'Seeder normalized this product to 50 units.',
                    'created_by' => $admin->id,
                    'created_at' => now(),
                    'shop_id' => $shop->id,
                    'balance_after' => 50,
                    'reason_code' => 'seed_stock_50',
                ]);
            }
            $product->updateTotalCount();
        }
    }

    private function seedDailySummaries(): void
    {
        for ($daysAgo = 29; $daysAgo >= 0; $daysAgo--) {
            $date = now()->subDays($daysAgo)->toDateString();
            $orders = Order::whereDate('created_at', $date)->get();
            $valid = $orders->where('status', '!=', 'cancelled');
            DailySalesSummary::updateOrCreate(
                ['date' => $date],
                [
                    'total_orders' => $orders->count(),
                    'cancelled_orders' => $orders->where('status', 'cancelled')->count(),
                    'total_revenue' => $valid->sum(fn ($order) => (float) $order->grand_total),
                    'total_cogs' => $valid->sum(fn ($order) => (float) $order->total_cogs),
                    'gross_profit' => $valid->sum(fn ($order) => (float) $order->gross_profit),
                    'total_refunds' => $valid->sum(fn ($order) => (float) $order->refund_total),
                    'total_items_sold' => OrderItem::whereIn('order_id', $valid->pluck('id'))->sum('quantity'),
                    'district_breakdown' => $valid->groupBy('checkout_district')->map->count()->all(),
                ]
            );
        }
    }

    private function orderStatus(int $index): string
    {
        if ($index % 20 === 0) return 'cancelled';
        if ($index % 11 === 0) return 'pending';
        if ($index % 7 === 0) return 'processing';
        if ($index % 5 === 0) return 'confirmed';
        return $index % 2 === 0 ? 'completed' : 'delivered';
    }

    private function paymentState(int $index, string $status, float $grandTotal): array
    {
        if ($status === 'cancelled' || $status === 'pending') return ['unpaid', 0.0];
        if ($index % 9 === 0) return ['partial', round($grandTotal * 0.6, 2)];
        return ['paid', $grandTotal];
    }
