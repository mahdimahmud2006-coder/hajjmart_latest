import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = path.resolve(import.meta.dirname, "..");
const project = path.resolve(root, "..");
const read = (relative) => fs.readFileSync(path.join(project, relative), "utf8");
const stores = read("frontend/src/app/admin/(panel)/stores/page.tsx");
const employees = read("frontend/src/app/admin/(panel)/employees/page.tsx");
const routes = read("backend/routes/api.php");
const storeController = read("backend/app/Http/Controllers/Api/V1/Admin/StoreController.php");
const employeeController = read("backend/app/Http/Controllers/Api/V1/Admin/EmployeeController.php");
const i18n = read("frontend/src/lib/admin-i18n.ts");
const css = read("frontend/src/app/globals.css");
const more = read("frontend/src/app/admin/(panel)/more/page.tsx");

const checks = [];
const check = (name, condition) => checks.push({ name, ok: Boolean(condition) });

check("Stores remains under More", more.includes('href: "/admin/stores"'));
check("Employees remains under More", more.includes('href: "/admin/employees"'));
check("Store create uses real POST", stores.includes('adminRequest<AdminStore>("/stores", { method: "POST"'));
check("Store edit uses real PUT", stores.includes('`/stores/${selected.id}`') && stores.includes('method: "PUT"'));
check("Store form is single column", stores.includes('admin-prd09-form') && !stores.includes("<FormGrid"));
check("Store edit includes default fulfilment toggle", stores.includes('name="is_default"'));
check("Store delete is Admin-only in UI", stores.includes('isAdmin && <Panel title={t("stores.dangerZone")'));
check("Store delete uses entity-specific Dialog", stores.includes('<Dialog open={deleteOpen') && stores.includes('`${t("stores.delete")} ${selected.name}?`'));
check("Store delete backend is Admin-only", /Route::delete\('\/stores\/\{store\}'[^\n]+EnsureAdmin::class/.test(routes));
check("Default store delete guard preserved", storeController.includes("abort_if($store->is_default"));
check("Store order/stock delete guard preserved", storeController.includes("$store->orders()->exists()") && storeController.includes("inventory()->where('quantity', '>', 0)->exists()"));
check("Store activation is immediate PUT", stores.includes('setStoreActive') && stores.includes('body: { is_active: nextActive }'));
check("Store activation offers Undo", stores.includes('actionLabel: t("stores.undo")'));
check("Store available inventory subtracts reserved", storeController.includes('quantity - (int) $inventory->reserved'));
check("Store employee count includes employees only", storeController.includes("where('is_employee', true)"));
check("Store detail links to inventory", stores.includes('/admin/inventory?shop_id=${selected.id}'));

check("Employee Add visible only to Admin", employees.includes('actions={isAdmin ? <AdminButton'));
check("Employee create endpoint is Admin-only", /Route::post\('\/employees'[^\n]+EnsureAdmin::class/.test(routes));
check("Employee update endpoint is Admin-only", /Route::put\('\/employees\/\{employee\}'[^\n]+EnsureAdmin::class/.test(routes));
check("Employee password endpoint is Admin-only", /employees\/\{employee\}\/password[^\n]+EnsureAdmin::class/.test(routes));
check("Employee toggle endpoint is Admin-only", /employees\/\{employee\}\/toggle[^\n]+EnsureAdmin::class/.test(routes));
check("Employee delete endpoint is Admin-only", /Route::delete\('\/employees\/\{employee\}'[^\n]+EnsureAdmin::class/.test(routes));
check("Employee create form has real login password helper", i18n.includes('"employees.passwordHelper": "This is the password the employee will use to sign in."'));
check("Employee UI has no fake Export", !employees.includes("Export") && !employees.includes('icon="download"'));
check("Employee form has no role/permission/employment type fields", !/name="(role|permission|employment_type)"/.test(employees));
check("Employee list uses Admin or Employee account level", employees.includes('employees.admin') && employees.includes('employees.employeeLevel'));
check("Normal employee detail remains viewable", routes.includes("Route::get('/employees/{employee}', [AdminEmployeeController::class, 'show']);"));
check("Normal employees see no account controls", employees.includes('{isAdmin && <>'));
check("Change password requires no old password", employees.includes('name="password"') && employees.includes('name="password_confirmation"') && !employees.includes('old_password'));
check("Password change revokes target sessions", employeeController.includes('$employee->tokens()->delete();'));
check("Self admin-level change blocked", employeeController.includes('Another administrator must change your administrator status.'));
check("Last active Admin safety preserved", employeeController.includes('guardLastActiveAdministrator') && employeeController.includes('At least one active administrator must remain.'));
check("Self deactivation blocked", employeeController.includes('You cannot deactivate your own account.'));
check("Disable uses plain confirmation Dialog", employees.includes('<Dialog open={disableOpen') && employees.includes('employees.disableDescription'));
check("Employee delete uses existing soft delete model", read("backend/app/Models/User.php").includes('use HasFactory, Notifiable, HasApiTokens, SoftDeletes;'));
check("Home Store copy says it does not limit access", i18n.includes('It does not limit which stores or pages this employee can use.'));
check("Last login is displayed", employees.includes('selected.last_login_at') && employees.includes('formatDate(selected.last_login_at, true)'));
check("Employees have mobile cards", employees.includes('<DataList desktop={desktop} mobile={mobile}'));
check("Stores have mobile cards", stores.includes('<DataList desktop={desktop} mobile={mobile}'));
check("PRD09 mobile breakpoint exists", css.includes('/* PRD-09: Stores & Employees */') && css.includes('@media (max-width: 599px)'));
check("PRD09 readable card text stays 16px primary", css.includes('.admin-prd09-card strong { font-size: 16px;') && css.includes('.admin-prd09-card > span { color: var(--neutral-600); font-size: 16px;'));
check("EN Store translations exist", i18n.includes('"stores.saveChanges": "Save Store Changes"'));
check("Bangla Store translations exist", i18n.includes('"stores.saveChanges": "স্টোরের পরিবর্তন সংরক্ষণ করুন"'));
check("EN Employee translations exist", i18n.includes('"employees.changePassword": "Change Password"'));
check("Bangla Employee translations exist", i18n.includes('"employees.changePassword": "পাসওয়ার্ড পরিবর্তন করুন"'));
check("No forgot-password UI added", !stores.toLowerCase().includes("forgot password") && !employees.toLowerCase().includes("forgot password"));

const failed = checks.filter((item) => !item.ok);
for (const item of checks) console.log(`${item.ok ? "PASS" : "FAIL"} ${item.name}`);
console.log(`\nPRD-09 contract: ${checks.length - failed.length}/${checks.length} passed`);
if (failed.length) process.exit(1);
